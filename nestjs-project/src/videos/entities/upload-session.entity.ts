import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryColumn,
  UpdateDateColumn,
} from 'typeorm';
import { bigintNumberTransformer } from '../../database/bigint-number.transformer';
import { UploadPart } from './upload-part.entity';
import { Video } from './video.entity';

/** `initiating` refines the states proposed by TD-02 (P1). */
export enum UploadSessionStatus {
  INITIATING = 'initiating',
  ACTIVE = 'active',
  COMPLETING = 'completing',
  COMPLETED = 'completed',
  ABORTING = 'aborting',
  ABORTED = 'aborted',
}

@Entity('upload_sessions')
@Index('IDX_upload_sessions_status_expires_at', ['status', 'expires_at'])
@Index('IDX_upload_sessions_status_claim_expires_at', [
  'status',
  'claim_expires_at',
])
// Extra defense against bugs only: sessions in `initiating`, `completing` or `aborting` stay out
// of it, so the real mutual exclusion comes from P1 and P2.
@Index('UQ_upload_sessions_video_id_active', ['video_id'], {
  unique: true,
  where: `"status" = 'active'`,
})
export class UploadSession {
  /**
   * Generated by the server in step T1 of P1, before any storage call, because `object_key`
   * (`originals/{videoId}/{sessionId}`) is written in the same INSERT. There is no database
   * default, so a session without an explicit id is refused.
   */
  @PrimaryColumn({ type: 'uuid' })
  id: string;

  @Column({ type: 'uuid' })
  video_id: string;

  @Column({ type: 'varchar', length: 255, unique: true })
  object_key: string;

  /** Null while the session is `initiating`. */
  @Column({ type: 'text', nullable: true })
  upload_id: string | null;

  @Column({
    type: 'enum',
    enum: UploadSessionStatus,
    default: UploadSessionStatus.INITIATING,
  })
  status: UploadSessionStatus;

  @Column({ type: 'bigint', transformer: bigintNumberTransformer })
  size_bytes: number;

  @Column({ type: 'integer' })
  part_size: number;

  @Column({ type: 'integer' })
  part_count: number;

  @Column({ type: 'varchar', length: 16, default: 'SHA256' })
  checksum_algorithm: string;

  @Column({ type: 'timestamptz' })
  expires_at: Date;

  @Column({ type: 'uuid', nullable: true })
  claim_token: string | null;

  @Column({ type: 'timestamptz', nullable: true })
  claim_expires_at: Date | null;

  @Column({ type: 'timestamptz', nullable: true })
  file_mismatch_at: Date | null;

  @CreateDateColumn({ type: 'timestamptz' })
  created_at: Date;

  @UpdateDateColumn({ type: 'timestamptz' })
  updated_at: Date;

  @ManyToOne(() => Video, (video) => video.upload_sessions, {
    onDelete: 'CASCADE',
  })
  @JoinColumn({ name: 'video_id' })
  video: Video;

  @OneToMany(() => UploadPart, (part) => part.upload_session)
  parts: UploadPart[];
}
