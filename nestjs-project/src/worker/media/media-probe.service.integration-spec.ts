jest.setTimeout(30_000);

/** The fixtures of SI-03.6 (V-04), generated by `generate.sh` with the FFmpeg of the image. */
const FIXTURES = join(
  __dirname,
  '..',
  '..',
  '..',
  'test',
  'fixtures',
  'videos',
);

async function createModule(timeoutMs?: number): Promise<TestingModule> {
  let builder = Test.createTestingModule({
    imports: [
      ConfigModule.forRoot({
        isGlobal: true,
        load: [storageConfig, queueConfig],
      }),
      StorageModule,
    ],
    providers: [MediaProbeService, MediaProcessRunner],
  });
  if (timeoutMs !== undefined) {
    const config = queueConfig();
    builder = builder.overrideProvider(queueConfig.KEY).useValue({
      ...config,
      videoProcessing: { ...config.videoProcessing, timeoutMs },
    });
  }
  return builder.compile();
}

/** Whether a process with this exact name runs in the container of the tests. */
function processRunning(name: string): boolean {
  return spawnSync('pgrep', ['-x', name]).status === 0;
}

/** A server that accepts connections and never sends a byte, as a stalled storage. */
async function startStalledServer(): Promise<{
  server: Server;
  port: number;
  connections: () => number;
  close: () => Promise<void>;
}> {
  const sockets = new Set<Socket>();
  let accepted = 0;
  const server = createServer((socket) => {
    accepted += 1;
    sockets.add(socket);
    socket.on('close', () => sockets.delete(socket));
    socket.on('error', () => undefined);
  });
  await new Promise<void>((resolve) =>
    server.listen(0, '127.0.0.1', () => resolve()),
  );
  const address = server.address();
  if (address === null || typeof address === 'string') {
    throw new Error('The stalled server has no port');
  }
  return {
    server,
    port: address.port,
    connections: () => accepted,
    close: () =>
      new Promise<void>((resolve) => {
        sockets.forEach((socket) => socket.destroy());
        server.close(() => resolve());
      }),
  };
}

describe('MediaProbeService (integration)', () => {
  const config = storageConfig();
  const s3 = createStorageClient(config, config.endpoint);
  const prefix = createStorageTestPrefix('media-probe');
  let moduleRef: TestingModule;
  let service: MediaProbeService;
  let storage: StorageService;

  beforeAll(async () => {
    moduleRef = await createModule();
    service = moduleRef.get(MediaProbeService);
    storage = moduleRef.get(StorageService);
    for (const fixture of [
      'h264-aac-faststart.mp4',
      'h264-aac-moov-end.mp4',
      'h264-no-audio.mp4',
      'vp9-opus.webm',
      'qt-brand.mov',
      'invalid.mp4',
      'truncated.mp4',
    ]) {
      const body = readFileSync(join(FIXTURES, fixture));
      await s3.send(
        new PutObjectCommand({
          Bucket: config.bucket,
          Key: `${prefix}${fixture}`,
          Body: body,
          ContentLength: body.length,
        }),
      );
    }
  });

  afterAll(async () => {
    try {
      await cleanupStoragePrefix(prefix);
    } finally {
      s3.destroy();
      await moduleRef.close();
    }
  });

  afterEach(() => {
    jest.restoreAllMocks();
  });

  /** The warnings of the service; the TestingLogger of Nest does not print them. */
  function captureWarnings(): () => string {
    const warn = jest
      .spyOn(Logger.prototype, 'warn')
      .mockImplementation(() => undefined);
    return () => warn.mock.calls.map(([message]) => String(message)).join('\n');
  }

  /** The JPEG decodes as an MJPEG image of the dimensions of the video. */
  function decodeJpeg(data: Buffer): {
    codec?: string;
    width?: number;
    height?: number;
  } {
    const file = join(
      tmpdir(),
      `media-probe-frame-${process.pid}-${Date.now()}.jpg`,
    );
    writeFileSync(file, data);
    try {
      const result = spawnSync(
        'ffprobe',
        ['-v', 'error', '-print_format', 'json', '-show_streams', file],
        { encoding: 'utf8' },
      );
      const stream = (
        JSON.parse(result.stdout) as {
          streams: { codec_name?: string; width?: number; height?: number }[];
        }
      ).streams[0];
      return {
        codec: stream.codec_name,
        width: stream.width,
        height: stream.height,
      };
    } finally {
      rmSync(file, { force: true });
    }
  }

  describe('accepted media, read by Range over the internal presigned URL', () => {
    it.each([
      ['h264-aac-faststart.mp4', 'video/mp4', 'h264', 'aac', 2],
      ['h264-aac-moov-end.mp4', 'video/mp4', 'h264', 'aac', 2],
      ['h264-no-audio.mp4', 'video/mp4', 'h264', null, 2],
      ['vp9-opus.webm', 'video/webm', 'vp9', 'opus', 2.008],
    ])(
      'should accept %s with its duration, dimensions and codecs',
      async (fixture, contentType, videoCodec, audioCodec, duration) => {
        const metadata = await service.probe(
          `${prefix}${fixture}`,
          contentType,
        );

        expect(metadata).toMatchObject({
          width: 320,
          height: 240,
          videoCodec,
          audioCodec,
        });
        expect(metadata.durationSeconds).toBeCloseTo(duration, 3);
        expect(metadata.mediaFormat).toContain(
          contentType === 'video/mp4' ? 'mp4' : 'webm',
        );
      },
    );

    it.each(['h264-aac-moov-end.mp4', 'vp9-opus.webm'])(
      'should extract a valid JPEG frame of %s',
      async (fixture) => {
        const frame = await service.extractFrame(`${prefix}${fixture}`, 1);

        expect(frame.subarray(0, 2)).toEqual(Buffer.from([0xff, 0xd8]));
        expect(frame.subarray(-2)).toEqual(Buffer.from([0xff, 0xd9]));
        expect(decodeJpeg(frame)).toEqual({
          codec: 'mjpeg',
          width: 320,
          height: 240,
        });
      },
    );
  });

  describe('refused media (permanent)', () => {
    it('should refuse the MOV declared as MP4 by its major_brand', async () => {
      const error = await service
        .probe(`${prefix}qt-brand.mov`, 'video/mp4')
        .catch((caught: unknown) => caught);

      expect(error).toBeInstanceOf(MediaRejectedError);
      expect(error).toMatchObject({ code: 'MEDIA_CONTAINER_MISMATCH' });
      expect((error as MediaRejectedError).reason).toMatch(
        /major_brand qt {2}/,
      );
    });

    it.each([
      ['invalid.mp4', /Invalid data found when processing input/],
      ['truncated.mp4', /moov atom not found/],
    ])(
      'should refuse %s as MEDIA_INVALID by the message of the demuxer, without the signed query',
      async (fixture, cause) => {
        const warnings = captureWarnings();
        const error = await service
          .probe(`${prefix}${fixture}`, 'video/mp4')
          .catch((caught: unknown) => caught);

        expect(error).toBeInstanceOf(MediaRejectedError);
        expect(error).toMatchObject({ code: 'MEDIA_INVALID' });
        expect((error as MediaRejectedError).reason).toMatch(cause);
        expect((error as MediaRejectedError).reason).not.toMatch(/X-Amz-/);
        expect(warnings()).toContain(`${prefix}${fixture}`);
        expect(warnings()).toMatch(cause);
        expect(warnings()).not.toMatch(/X-Amz-/);
      },
    );
  });

  describe('transient failures', () => {
    it('should give a missing object (404 of the storage) as transient, never as MEDIA_INVALID', async () => {
      const warnings = captureWarnings();
      const error = await service
        .probe(`${prefix}missing.mp4`, 'video/mp4')
        .catch((caught: unknown) => caught);

      expect(error).toBeInstanceOf(MediaTransientError);
      expect((error as MediaTransientError).reason).toMatch(
        /Server returned 404/,
      );
      expect((error as MediaTransientError).reason).not.toMatch(/X-Amz-/);
      expect(warnings()).toMatch(/Server returned 404/);
      expect(warnings()).not.toMatch(/X-Amz-/);
    });

    it('should end ffprobe and ffmpeg by themselves against a server that sends no bytes, as transient, within the per-call timeout (T-13)', async () => {
      const stalled = await startStalledServer();
      const { url } = await storage.presignGet({
        key: `${prefix}h264-aac-moov-end.mp4`,
        audience: 'internal',
        expiresInSeconds: 300,
      });
      const stalledUrl = new URL(url);
      stalledUrl.host = `127.0.0.1:${stalled.port}`;
      jest.spyOn(storage, 'presignGet').mockResolvedValue({
        url: stalledUrl.toString(),
        expiresAt: new Date(),
      });
      try {
        const timed = async (call: Promise<unknown>) => {
          const startedAt = Date.now();
          const error = await call.catch((caught: unknown) => caught);
          return { error, ms: Date.now() - startedAt };
        };

        const [probe, frame] = await Promise.all([
          timed(service.probe(`${prefix}h264-aac-moov-end.mp4`, 'video/mp4')),
          timed(service.extractFrame(`${prefix}h264-aac-moov-end.mp4`, 1)),
        ]);

        for (const { error, ms } of [probe, frame]) {
          expect(error).toBeInstanceOf(MediaTransientError);
          expect((error as MediaTransientError).reason).toMatch(
            /Connection timed out/,
          );
          expect((error as MediaTransientError).reason).not.toMatch(/X-Amz-/);
          // 4 connections × 10 s of rw_timeout + waits of 0, 1 and 3 s (V-04: 44.6 s).
          expect(ms).toBeGreaterThanOrEqual(40_000);
          expect(ms).toBeLessThan(50_000);
        }
        expect(stalled.connections()).toBe(8);
        expect(processRunning('ffprobe')).toBe(false);
        expect(processRunning('ffmpeg')).toBe(false);
      } finally {
        await stalled.close();
      }
    }, 70_000);

    it('should kill the process at the per-call timeout and wait for its end, leaving none behind', async () => {
      const stalled = await startStalledServer();
      const shortTimeout = await createModule(3_000);
      const shortService = shortTimeout.get(MediaProbeService);
      jest
        .spyOn(shortTimeout.get(StorageService), 'presignGet')
        .mockResolvedValue({
          url: `http://127.0.0.1:${stalled.port}/streamtube/stalled.mp4?X-Amz-Signature=secret`,
          expiresAt: new Date(),
        });
      try {
        for (const [name, call] of [
          ['ffprobe', () => shortService.probe('stalled.mp4', 'video/mp4')],
          ['ffmpeg', () => shortService.extractFrame('stalled.mp4', 1)],
        ] as const) {
          const startedAt = Date.now();
          const pending = call().catch((caught: unknown) => caught);
          // Positive control: the check below sees the process while it runs.
          await new Promise((resolve) => setTimeout(resolve, 1_000));
          expect(processRunning(name)).toBe(true);
          const error = await pending;
          const ms = Date.now() - startedAt;

          expect(error).toBeInstanceOf(MediaTransientError);
          expect((error as MediaTransientError).reason).toMatch(
            /per-call timeout/,
          );
          expect(ms).toBeGreaterThanOrEqual(3_000);
          expect(ms).toBeLessThan(5_000);
          expect(processRunning('ffprobe')).toBe(false);
          expect(processRunning('ffmpeg')).toBe(false);
        }
      } finally {
        await stalled.close();
        await shortTimeout.close();
      }
    });
  });
});
