import { randomUUID } from 'node:crypto';
import type { DataSource } from 'typeorm';
import { Channel } from '../channels/entities/channel.entity';
import { VIDEO_DEFAULTS } from '../config/config.constants';
import { User } from '../users/entities/user.entity';
import { UploadPart } from '../videos/entities/upload-part.entity';
import {
  UploadSession,
  UploadSessionStatus,
} from '../videos/entities/upload-session.entity';
import { Video } from '../videos/entities/video.entity';

let sequence = 0;
const nextSequence = (): number => ++sequence;

/** User and channel that own the videos of an entity test. */
export async function saveTestChannel(
  dataSource: DataSource,
): Promise<Channel> {
  const n = nextSequence();
  const user = await dataSource.getRepository(User).save({
    email: `video_owner_${n}@example.com`,
    password: 'hashed',
  });
  return dataSource.getRepository(Channel).save({
    name: `Channel ${n}`,
    nickname: `video_owner_${n}`,
    user_id: user.id,
  });
}

/** 11 characters, like the public ids generated by the service (TD-05). */
export function testPublicId(): string {
  return `v${String(nextSequence()).padStart(10, '0')}`;
}

export function buildVideo(
  channelId: string,
  overrides: Partial<Video> = {},
): Partial<Video> {
  return {
    public_id: testPublicId(),
    channel_id: channelId,
    original_filename: 'video.mp4',
    content_type: 'video/mp4',
    size_bytes: 1_048_576,
    ...overrides,
  };
}

/** Session in `initiating`, with the id and key generated before the INSERT, as in T1 of P1. */
export function buildUploadSession(
  videoId: string,
  overrides: Partial<UploadSession> = {},
): Partial<UploadSession> {
  const id = overrides.id ?? randomUUID();
  return {
    id,
    video_id: videoId,
    object_key: `originals/${videoId}/${id}`,
    status: UploadSessionStatus.INITIATING,
    size_bytes: 1_048_576,
    part_size: VIDEO_DEFAULTS.UPLOAD_PART_SIZE_BYTES,
    part_count: 1,
    expires_at: new Date(Date.now() + 60_000),
    claim_token: randomUUID(),
    claim_expires_at: new Date(Date.now() + 60_000),
    ...overrides,
  };
}

export function buildUploadPart(
  uploadSessionId: string,
  overrides: Partial<UploadPart> = {},
): Partial<UploadPart> {
  return {
    upload_session_id: uploadSessionId,
    part_number: 1,
    expected_size: 1_048_576,
    checksum_sha256: 'A'.repeat(43) + '=',
    ...overrides,
  };
}
