/** The fixtures of SI-03.6 (V-04), generated by `generate.sh` with the FFmpeg of the image. */
export const VIDEO_FIXTURES = join(
  __dirname,
  '..',
  '..',
  'test',
  'fixtures',
  'videos',
);

/** Uploads a fixture as the confirmed original of a video, at a key of the phase layout. */
export async function uploadOriginal(
  s3: S3Client,
  bucket: string,
  videoId: string,
  fixture: string,
): Promise<string> {
  const key = `originals/${videoId}/${randomUUID()}`;
  const body = readFileSync(join(VIDEO_FIXTURES, fixture));
  await s3.send(
    new PutObjectCommand({
      Bucket: bucket,
      Key: key,
      Body: body,
      ContentLength: body.length,
    }),
  );
  return key;
}

/** A video as P2 leaves it after the completion: `processing`, run 1, generation 1, no attempt. */
export async function saveProcessingVideo(
  dataSource: DataSource,
  channelId: string,
  overrides: Partial<Video> = {},
): Promise<Video> {
  return dataSource.getRepository(Video).save(
    buildVideo(channelId, {
      status: VideoStatus.PROCESSING,
      processing_run: 1,
      processing_dispatch: 1,
      processing_started_at: new Date(),
      ...overrides,
    }),
  );
}

export async function reloadVideo(
  dataSource: DataSource,
  id: string,
): Promise<Video> {
  return dataSource.getRepository(Video).findOneByOrFail({ id });
}

export interface DeliveryOptions {
  run?: number;
  dispatch?: number;
  /** `job.attemptsStarted`, the `seq` of the order token. */
  seq?: number;
  attemptsMade?: number;
  attempts?: number;
}

/**
 * A delivery of `process-video` as the processor reads it, to call `process` directly with a
 * controlled token: the jobId of the generation, the payload and the counters of BullMQ.
 */
export function deliveryOf(
  videoId: string,
  options: DeliveryOptions = {},
): Job<ProcessVideoJobData> {
  const { run = 1, dispatch = 1, seq = 1, attempts = 3 } = options;
  return {
    id: buildVideoJobId({ videoId, run, dispatch }),
    data: { videoId, run },
    attemptsStarted: seq,
    attemptsMade: options.attemptsMade ?? seq - 1,
    opts: { attempts },
  } as Job<ProcessVideoJobData>;
}

/** Body and content type of an object of the bucket. */
export async function readObject(
  s3: S3Client,
  bucket: string,
  key: string,
): Promise<{ body: Buffer; contentType: string | undefined }> {
  const output = await s3.send(
    new GetObjectCommand({ Bucket: bucket, Key: key }),
  );
  const bytes = await output.Body!.transformToByteArray();
  return { body: Buffer.from(bytes), contentType: output.ContentType };
}

/** Decodes an image with ffprobe: codec and dimensions, or `null` when it is not decodable. */
export function decodeImage(
  data: Buffer,
): { codec?: string; width?: number; height?: number } | null {
  const file = join(tmpdir(), `processing-${process.pid}-${randomUUID()}.jpg`);
  writeFileSync(file, data);
  try {
    const result = spawnSync(
      'ffprobe',
      ['-v', 'error', '-print_format', 'json', '-show_streams', file],
      { encoding: 'utf8' },
    );
    if (result.status !== 0) {
      return null;
    }
    const [stream] = (
      JSON.parse(result.stdout) as {
        streams: { codec_name?: string; width?: number; height?: number }[];
      }
    ).streams;
    return {
      codec: stream?.codec_name,
      width: stream?.width,
      height: stream?.height,
    };
  } finally {
    rmSync(file, { force: true });
  }
}

/** Keys of the thumbnails written for a video, by any attempt. */
export function thumbnailKeysOf(
  s3: S3Client,
  bucket: string,
  videoId: string,
): Promise<string[]> {
  return listKeysUnder(s3, bucket, `thumbnails/${videoId}/`);
}

/** Deletes the originals and thumbnails of every video in the database. */
export async function removeStorageOfVideos(
  dataSource: DataSource,
  s3: S3Client,
  bucket: string,
): Promise<void> {
  for (const video of await dataSource.getRepository(Video).find()) {
    for (const prefix of [
      `originals/${video.id}/`,
      `thumbnails/${video.id}/`,
    ]) {
      for (const key of await listKeysUnder(s3, bucket, prefix)) {
        await s3.send(new DeleteObjectCommand({ Bucket: bucket, Key: key }));
      }
    }
  }
}
